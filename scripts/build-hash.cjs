const fs=require('node:fs');
const esbuild=require('esbuild');
(async()=>{
 const result=await esbuild.build({entryPoints:['scripts/hash-entry.mjs'],bundle:true,write:false,minify:true,platform:'browser',format:'iife',target:'es2020',legalComments:'inline'});
 const license=fs.readFileSync('resources/HASH-LICENSE.txt','utf8');
 const output='/* @noble/hashes 1.8.0; generated by npm run build:hash.\n'+license+'\n*/\n'+result.outputFiles[0].text;
 if(process.argv.includes('--check')){if(!fs.existsSync('resources/hash.js')||fs.readFileSync('resources/hash.js','utf8')!==output)throw new Error('resources/hash.js is out of date; run npm run build:hash');}
 else fs.writeFileSync('resources/hash.js',output);
})().catch(e=>{console.error(e);process.exitCode=1;});
